/** @jest-environment node */
// @ts-check
import path from "node:path";
import { jest } from "@jest/globals";

const execute = jest.fn();
const mkdir = jest.fn();
const writeFile = jest.fn();
const unlink = jest.fn();

jest.unstable_mockModule("@dwtechs/antity-pgsql", () => ({ execute }));
jest.unstable_mockModule("node:fs/promises", () => ({
  mkdir,
  writeFile,
  unlink,
}));

const { saveLogo, LOGO_FILE_RE } = await import(
  "../../src/services/branding-logo.js"
);

const CONSUMER = { userId: 7, nickname: "admin" };
const LOGO = { buffer: Buffer.from("x"), ext: "png" };
const OLD_FILE = `logo-${"a".repeat(8)}-aaaa-aaaa-aaaa-${"a".repeat(12)}.svg`;

describe("saveLogo", () => {
  beforeEach(() => {
    jest.resetAllMocks();
    mkdir.mockResolvedValue(undefined);
    writeFile.mockResolvedValue(undefined);
    unlink.mockResolvedValue(undefined);
  });

  it("should store the file under a generated name and return the updated row", async () => {
    execute.mockResolvedValue({
      rows: [{ id: 1, logoFile: "new", previousLogoFile: "" }],
    });

    const row = await saveLogo(1, CONSUMER, LOGO);

    const written = String(writeFile.mock.calls[0][0]);
    const name = path.basename(written);
    expect(name).toMatch(LOGO_FILE_RE);
    expect(execute.mock.calls[0][1]).toEqual([name, 7, "admin", 1]);
    expect(row).toEqual({ id: 1, logoFile: "new" });
    expect(unlink).not.toHaveBeenCalled();
  });

  it("should delete the previous file once the row is updated", async () => {
    execute.mockResolvedValue({
      rows: [{ id: 1, logoFile: "new", previousLogoFile: OLD_FILE }],
    });

    await saveLogo(1, CONSUMER, LOGO);

    expect(String(unlink.mock.calls[0][0])).toMatch(new RegExp(`${OLD_FILE}$`));
  });

  it("should never delete a previous name that was not generated by the upload", async () => {
    execute.mockResolvedValue({
      rows: [{ id: 1, logoFile: "new", previousLogoFile: "../../etc/passwd" }],
    });

    await saveLogo(1, CONSUMER, LOGO);

    expect(unlink).not.toHaveBeenCalled();
  });

  it("should remove the new file and return null when the row does not exist", async () => {
    execute.mockResolvedValue({ rows: [] });

    expect(await saveLogo(9, CONSUMER, LOGO)).toBeNull();
    const written = String(writeFile.mock.calls[0][0]);
    expect(unlink).toHaveBeenCalledWith(written);
  });

  it("should remove the new file and rethrow when the update fails", async () => {
    const err = new Error("db down");
    execute.mockRejectedValue(err);

    await expect(saveLogo(1, CONSUMER, LOGO)).rejects.toBe(err);
    expect(unlink).toHaveBeenCalledWith(String(writeFile.mock.calls[0][0]));
  });
});
