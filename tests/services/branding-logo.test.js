/** @jest-environment node */
// @ts-check
import path from "node:path";
import { jest } from "@jest/globals";

const execute = jest.fn();
const mkdir = jest.fn();
const writeFile = jest.fn();
const unlink = jest.fn();
const select = jest.fn();
const update = jest.fn();

jest.unstable_mockModule("@dwtechs/antity-pgsql", () => ({ execute }));
jest.unstable_mockModule("../../src/entities/branding.js", () => ({
  default: { query: { select, update } },
}));
jest.unstable_mockModule("node:fs/promises", () => ({
  mkdir,
  writeFile,
  unlink,
}));

const {
  saveLogo,
  deleteLogo,
  saveFavicon,
  deleteFavicon,
  LOGO_FILE_RE,
  FAVICON_FILE_RE,
} = await import("../../src/services/branding-logo.js");

const CONSUMER = { userId: 7, nickname: "admin" };
const LOGO = { buffer: Buffer.from("x"), ext: "png" };
const OLD_FILE = `logo-${"a".repeat(8)}-aaaa-aaaa-aaaa-${"a".repeat(12)}.svg`;
const OLD_FAVICON = `favicon-${"b".repeat(8)}-bbbb-bbbb-bbbb-${"b".repeat(12)}.png`;

/** Queues the rows returned by successive entity selects (before / after update). */
const selects = (...rows) => {
  const queue = [...rows];
  select.mockReturnValue({ query: "SELECT", args: [] });
  execute.mockImplementation(async (query) => {
    if (query !== "SELECT") return { rows: [] };
    const row = queue.shift();
    return { rows: row ? [row] : [] };
  });
};

beforeEach(() => {
  jest.resetAllMocks();
  mkdir.mockResolvedValue(undefined);
  writeFile.mockResolvedValue(undefined);
  unlink.mockResolvedValue(undefined);
  update.mockReturnValue({ query: "UPDATE", args: [] });
});

describe("saveLogo", () => {
  it("should store the file under a generated name and update the row through the entity", async () => {
    selects({ id: 1, logoFile: "" }, { id: 1, logoFile: "new" });

    const row = await saveLogo(1, CONSUMER, LOGO);

    const name = path.basename(String(writeFile.mock.calls[0][0]));
    expect(name).toMatch(LOGO_FILE_RE);
    expect(update).toHaveBeenCalledWith([{ id: 1, logoFile: name }], CONSUMER);
    expect(select.mock.calls[0][4]).toEqual({
      id: { value: 1, matchMode: "equals" },
      archived: { value: false, matchMode: "equals" },
    });
    expect(row).toEqual({ id: 1, logoFile: "new" });
    expect(unlink).not.toHaveBeenCalled();
  });

  it("should delete the previous file once the row is updated", async () => {
    selects({ id: 1, logoFile: OLD_FILE }, { id: 1, logoFile: "new" });

    await saveLogo(1, CONSUMER, LOGO);

    expect(String(unlink.mock.calls[0][0])).toMatch(new RegExp(`${OLD_FILE}$`));
  });

  it("should never delete a previous name that was not generated by the upload", async () => {
    selects({ id: 1, logoFile: "../../etc/passwd" }, { id: 1 });

    await saveLogo(1, CONSUMER, LOGO);

    expect(unlink).not.toHaveBeenCalled();
  });

  it("should return null without writing anything when the row does not exist", async () => {
    selects(null);

    expect(await saveLogo(9, CONSUMER, LOGO)).toBeNull();
    expect(writeFile).not.toHaveBeenCalled();
    expect(update).not.toHaveBeenCalled();
  });

  it("should remove the new file and rethrow when the update fails", async () => {
    const err = new Error("db down");
    selects({ id: 1, logoFile: "" });
    execute.mockImplementation(async (query) => {
      if (query === "UPDATE") throw err;
      return { rows: [{ id: 1, logoFile: "" }] };
    });

    await expect(saveLogo(1, CONSUMER, LOGO)).rejects.toBe(err);
    expect(unlink).toHaveBeenCalledWith(String(writeFile.mock.calls[0][0]));
  });
});

describe("deleteLogo", () => {
  it("should clear logoFile and remove the stored image", async () => {
    selects({ id: 1, logoFile: OLD_FILE }, { id: 1, logoFile: "" });

    const row = await deleteLogo(1, CONSUMER);

    expect(update).toHaveBeenCalledWith([{ id: 1, logoFile: "" }], CONSUMER);
    expect(String(unlink.mock.calls[0][0])).toMatch(new RegExp(`${OLD_FILE}$`));
    expect(row).toEqual({ id: 1, logoFile: "" });
  });
});

describe("saveFavicon", () => {
  it("should store the file under a favicon name and update the favicon columns", async () => {
    selects({ id: 1, faviconFile: "" }, { id: 1, faviconFile: "new" });

    const row = await saveFavicon(1, CONSUMER, LOGO);

    const name = path.basename(String(writeFile.mock.calls[0][0]));
    expect(name).toMatch(FAVICON_FILE_RE);
    expect(name).not.toMatch(LOGO_FILE_RE);
    expect(update).toHaveBeenCalledWith(
      [{ id: 1, faviconFile: name }],
      CONSUMER,
    );
    expect(row).toEqual({ id: 1, faviconFile: "new" });
  });

  it("should delete the previous favicon once the row is updated", async () => {
    selects({ id: 1, faviconFile: OLD_FAVICON }, { id: 1 });

    await saveFavicon(1, CONSUMER, LOGO);

    expect(String(unlink.mock.calls[0][0])).toMatch(
      new RegExp(`${OLD_FAVICON}$`),
    );
  });
});

describe("deleteFavicon", () => {
  it("should return null when the row is missing", async () => {
    selects(null);

    expect(await deleteFavicon(9, CONSUMER)).toBeNull();
    expect(update).not.toHaveBeenCalled();
    expect(unlink).not.toHaveBeenCalled();
  });
});
